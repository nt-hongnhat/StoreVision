package com.nthn.storevision.dto.analytics;

import io.swagger.v3.oas.annotations.media.Schema;
import java.math.BigDecimal;

/**
 * One row of the top-selling products report — only COMPLETED orders are counted (BR-A01).
 *
 * @param productId the product's identifier
 * @param productName the product's display name
 * @param quantitySold units sold within the reporting period; never {@code null}
 * @param revenue revenue generated by the product within the period; never {@code null}
 */
@Schema(description = "One row of the top-selling products report.")
public record TopSellingProductDTO(
    @Schema(description = "The product's identifier.", example = "1") Long productId,
    @Schema(description = "The product's display name.", example = "Wireless Mouse")
        String productName,
    @Schema(description = "Units sold within the reporting period (BR-A01).", example = "30")
        Long quantitySold,
    @Schema(description = "Revenue generated by the product within the period.", example = "8970000")
        BigDecimal revenue) {}
